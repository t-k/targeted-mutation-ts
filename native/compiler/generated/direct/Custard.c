TmtPulseCompiler_edit_plan
TmtPulseCompiler_arrow_plan(
  TmtPulseMemory_tape input,
  TmtGrammar_span name_span,
  TmtGrammar_span binding,
  uint32_t start
)
{
  TmtPulseParser_cursor head = TmtPulseParser_trivia(input, start);
  TmtPulseParser_cursor name = TmtPulseParser_name(input, head.at, false, true);
  if (!(head.ok && name.ok))
    return TmtPulseCompiler_declined();
  else
  {
    TmtPulseCompiler_annotation parameter = TmtPulseCompiler_annotation_after(input, name.at);
    TmtPulseParser_cursor close = TmtPulseParser_trivia(input, parameter.offset);
    bool closes = TmtPulseParser_same(input, close.at, 41U);
    if (!(parameter.valid && close.ok && closes))
      return TmtPulseCompiler_declined();
    else
    {
      uint32_t arrow_start = TmtPulseParser_next(close.at);
      TmtPulseParser_cursor after_close = TmtPulseParser_trivia(input, arrow_start);
      TmtPulseCompiler_annotation
      result_type = TmtPulseCompiler_annotation_after(input, arrow_start);
      TmtPulseParser_cursor arrow = TmtPulseParser_trivia(input, result_type.offset);
      bool equal = TmtPulseParser_same(input, arrow.at, 61U);
      bool greater = TmtPulseParser_same(input, TmtPulseParser_next(arrow.at), 62U);
      if
      (
        !(result_type.valid && after_close.ok && !after_close.newline && arrow.ok && !arrow.newline
        && equal
        && greater)
      )
        return TmtPulseCompiler_declined();
      else
      {
        TmtPulseParser_cursor
        tail = TmtPulseCompiler_expression_end(input, TmtPulseParser_plus(arrow.at, 2U));
        TmtPulseParser_cursor finish = TmtPulseCompiler_declaration_end(input, tail);
        if (finish.ok)
          return
            TmtPulseCompiler_make_plan(finish.at,
              name_span,
              binding,
              parameter.erased,
              result_type.erased);
        else
          return TmtPulseCompiler_declined();
      }
    }
  }
}

TmtPulseCompiler_edit_plan
TmtPulseCompiler_read_plan(TmtPulseMemory_tape input, uint32_t start)
{
  TmtPulseParser_cursor head = TmtPulseParser_trivia(input, start);
  bool exported = TmtPulseParser_keyword(input, head.at, 6U, 0x6578706f7274ULL);
  if (!(head.ok && exported))
    return TmtPulseCompiler_declined();
  else
  {
    TmtPulseParser_cursor kind = TmtPulseParser_trivia(input, TmtPulseParser_plus(head.at, 6U));
    bool constant = TmtPulseParser_keyword(input, kind.at, 5U, 0x636f6e7374ULL);
    if (!(kind.ok && constant))
      return TmtPulseCompiler_declined();
    else
    {
      TmtPulseParser_cursor
      name_start = TmtPulseParser_trivia(input, TmtPulseParser_plus(kind.at, 5U));
      TmtPulseParser_cursor name = TmtPulseParser_name(input, name_start.at, false, true);
      TmtPulseCompiler_annotation binding = TmtPulseCompiler_annotation_after(input, name.at);
      TmtPulseParser_cursor equal = TmtPulseParser_trivia(input, binding.offset);
      bool assigns = TmtPulseParser_same(input, equal.at, 61U);
      if (!(name_start.ok && name.ok && binding.valid && equal.ok && assigns))
        return TmtPulseCompiler_declined();
      else
      {
        TmtPulseParser_cursor init = TmtPulseParser_trivia(input, TmtPulseParser_next(equal.at));
        bool arrow = TmtPulseParser_same(input, init.at, 40U);
        TmtGrammar_span name_span = TmtPulseCompiler_range(name_start.at, name.at);
        if (!init.ok)
          return TmtPulseCompiler_declined();
        else if (arrow)
          return
            TmtPulseCompiler_arrow_plan(input,
              name_span,
              binding.erased,
              TmtPulseParser_next(init.at));
        else
        {
          TmtPulseParser_cursor end_ = TmtPulseCompiler_expression_end(input, init.at);
          TmtPulseParser_cursor finish = TmtPulseCompiler_declaration_end(input, end_);
          if (finish.ok)
            return
              TmtPulseCompiler_make_plan(finish.at,
                name_span,
                binding.erased,
                TmtPulseCompiler_empty_span,
                TmtPulseCompiler_empty_span);
          else
            return TmtPulseCompiler_declined();
        }
      }
    }
  }
}
